#!/usr/bin/env python3
"""Daily "propose a change, but only when something actually changed" bot.

Implements the ``todo.md`` requirement:

    use a github ci matrix to submit pull requests for this project daily
    (if no remote update, do not submit pull request)

The decision logic lives here — not in YAML — so it is unit-testable. The
GitHub Actions workflow only has to call::

    python3 scripts/daily_pr.py --repo owner/name --base dev

Behaviour
---------
1. Compute a content hash for every ``<platform>/<distro>/<python-version>``
   target.
2. Compare against the hash manifest committed at ``.ci/targets.json``.
3. If nothing changed  -> exit 0 and do nothing (no PR).
4. If something changed -> update the manifest, create a dated branch, commit,
   push, and open/refresh a pull request.
5. Never open a second PR when one is already open for the daily branch.

The GitHub token is read from ``GITHUB_TOKEN``/``GH_TOKEN`` (injected by
Actions) or from ``.env`` for local runs. It is never logged.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import json
import os
import pathlib
import subprocess
import sys
import urllib.error
import urllib.request

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_MANIFEST = REPO_ROOT / ".ci" / "targets.json"
API = "https://api.github.com"
TRACKING_ISSUE = 1


# --------------------------------------------------------------------------
# Pure decision logic (unit-tested)
# --------------------------------------------------------------------------

def should_open_pr(diff_lines: int, open_prs: int, force: bool = False) -> bool:
    """Decide whether the daily job should open a pull request.

    A PR is opened only when there is a real change to propose **and** no PR is
    already open (so the job cannot spam duplicates). ``force`` allows opening a
    PR with an empty diff, which is useful for testing the workflow itself.
    """
    if open_prs > 0:
        return False
    if force:
        return True
    return diff_lines > 0


def daily_branch_name(date: str) -> str:
    """Return the deterministic branch name for *date* (``YYYY-MM-DD``)."""
    return f"ci/daily-{date}"


def diff_targets(
    old: dict[str, str], new: dict[str, str]
) -> tuple[list[str], list[str], list[str]]:
    """Return ``(added, updated, removed)`` target names, each sorted."""
    added = sorted(k for k in new if k not in old)
    removed = sorted(k for k in old if k not in new)
    updated = sorted(k for k in new if k in old and old[k] != new[k])
    return added, updated, removed


def build_pr_body(
    added: list[str],
    updated: list[str],
    removed: list[str],
    issue: int | None = TRACKING_ISSUE,
) -> str:
    """Render the pull request body for a change set."""
    lines = [
        "Automated daily dependency-matrix refresh.",
        "",
        "Generated by `.github/workflows/daily.yml` via `scripts/daily_pr.py`.",
        "This PR is opened **only** because the tracked targets actually changed.",
        "",
    ]
    if issue:
        lines += [f"Refs #{issue}", ""]

    def section(title: str, items: list[str]) -> None:
        if items:
            lines.append(f"### {title}")
            lines.append("")
            lines.extend(f"- `{i}`" for i in items)
            lines.append("")

    section("Added", added)
    section("Updated", updated)
    section("Removed", removed)

    if not (added or updated or removed):
        lines += ["_No target content changed._", ""]

    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------
# Hashing
# --------------------------------------------------------------------------

def hash_directory(path: pathlib.Path) -> str:
    """Hash the meaningful content of a target directory.

    Skips virtualenvs, caches and other regenerable noise so the hash reflects
    real intent rather than machine state.
    """
    skip_dirs = {".venv", "venv", "__pycache__", ".pytest_cache", "node_modules",
                 ".mypy_cache", ".ruff_cache", ".uv-cache", "build", "dist"}
    digest = hashlib.sha256()
    for entry in sorted(path.rglob("*")):
        if any(part in skip_dirs for part in entry.parts):
            continue
        if entry.is_dir():
            continue
        if entry.name in {".DS_Store"} or entry.suffix in {".pyc", ".pyo"}:
            continue
        rel = entry.relative_to(path).as_posix()
        digest.update(rel.encode())
        digest.update(b"\0")
        try:
            digest.update(entry.read_bytes())
        except OSError:
            continue
        digest.update(b"\0")
    return digest.hexdigest()


def compute_manifest(root: pathlib.Path = REPO_ROOT) -> dict[str, str]:
    """Return ``{target: sha256}`` for every ``<platform>/<distro>/<pyver>``."""
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "check_layout", root / "scripts" / "check_layout.py"
    )
    cl = importlib.util.module_from_spec(spec)
    sys.modules["check_layout"] = cl
    spec.loader.exec_module(cl)

    manifest: dict[str, str] = {}
    for path, parts in cl.iter_target_dirs(root):
        manifest["/".join(parts)] = hash_directory(path)
    return manifest


def load_manifest(path: pathlib.Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    return data if isinstance(data, dict) else {}


def save_manifest(path: pathlib.Path, manifest: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


# --------------------------------------------------------------------------
# GitHub API
# --------------------------------------------------------------------------

def load_token() -> str | None:
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        return token.strip()
    env = REPO_ROOT / ".env"
    if env.is_file():
        for line in env.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            if key.strip() in {"GITHUB_TOKEN", "GH_TOKEN"}:
                return value.strip().strip('"').strip("'")
    return None


def api(method: str, path: str, token: str | None, data: dict | None = None):
    body = None if data is None else json.dumps(data).encode()
    req = urllib.request.Request(
        path if path.startswith("http") else API + path, data=body, method=method
    )
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("X-GitHub-Api-Version", "2022-11-28")
    req.add_header("User-Agent", "myjupyter-daily")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            raw = resp.read()
            return resp.status, (json.loads(raw) if raw else None)
    except urllib.error.HTTPError as exc:
        raw = exc.read()
        try:
            return exc.code, json.loads(raw)
        except Exception:
            return exc.code, {"message": raw.decode(errors="replace")}


def count_open_prs(repo: str, token: str | None, head_branch: str | None = None) -> int:
    query = f"/repos/{repo}/pulls?state=open&per_page=100"
    if head_branch:
        owner = repo.split("/")[0]
        query += f"&head={owner}:{head_branch}"
    status, payload = api("GET", query, token)
    if status != 200 or not isinstance(payload, list):
        print(f"warning: could not list PRs (status {status})", file=sys.stderr)
        return 0
    return len(payload)


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args], cwd=REPO_ROOT, check=check,
        capture_output=True, text=True,
    )


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", help="owner/name; required to open a PR")
    parser.add_argument("--base", default="dev", help="base branch (default: dev)")
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    parser.add_argument("--date", default=_dt.date.today().isoformat())
    parser.add_argument("--force", action="store_true",
                        help="open a PR even with no content change")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--issue", type=int, default=TRACKING_ISSUE)
    args = parser.parse_args(argv)

    manifest_path = pathlib.Path(args.manifest)
    old = load_manifest(manifest_path)
    new = compute_manifest()
    added, updated, removed = diff_targets(old, new)
    diff_lines = len(added) + len(updated) + len(removed)

    print(f"targets: {len(new)} | added {len(added)} updated {len(updated)} "
          f"removed {len(removed)}")

    token = load_token()
    branch = daily_branch_name(args.date)

    open_prs = 0
    if args.repo:
        open_prs = count_open_prs(args.repo, token, head_branch=branch)
        print(f"open PRs on {branch}: {open_prs}")

    if not should_open_pr(diff_lines=diff_lines, open_prs=open_prs, force=args.force):
        if diff_lines == 0:
            print("no remote update - not opening a pull request")
        else:
            print(f"changes present but {open_prs} PR(s) already open - skipping")
        return 0

    body = build_pr_body(added, updated, removed, issue=args.issue)
    print(f"changes detected - proposing a pull request on {branch}")

    if args.dry_run:
        print("--- would write manifest ---")
        print(json.dumps(new, indent=2, sort_keys=True))
        print("--- would open PR ---")
        print(body)
        return 0

    save_manifest(manifest_path, new)

    git("config", "user.name", "github-actions[bot]")
    git("config", "user.email", "41898282+github-actions[bot]@users.noreply.github.com")
    git("checkout", "-B", branch)
    git("add", str(manifest_path))
    git("commit", "-m", f"chore(ci): daily dependency matrix refresh {args.date}")

    if not args.repo:
        print("no --repo given; committed locally only")
        return 0

    git("push", "--force-with-lease", "-u", "origin", branch)

    status, payload = api(
        "POST", f"/repos/{args.repo}/pulls", token,
        {
            "title": f"chore(ci): daily dependency matrix refresh {args.date}",
            "head": branch,
            "base": args.base,
            "body": body,
        },
    )
    if status in (200, 201):
        print(f"opened PR: {payload.get('html_url')}")
    elif status == 422:
        print("a pull request for this branch already exists; nothing to do")
    else:
        print(f"failed to open PR (status {status}): {payload}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
